#!/usr/bin/env bash
# Build vk-rt-probe: cross-compiled for the Android guest by default, natively
# for macOS with --host.
#
# Two steps either way: the three GLSL shaders -> SPIR-V -> vk-rt-probe-spv.h (a
# plain uint32_t array, so the probe needs no files on the guest), then one clang
# invocation.
#
#   ./build-vk-rt-probe.sh            # aarch64-linux-android, for run-vk-rt-probe.sh
#   ./build-vk-rt-probe.sh --host     # arm64 macOS, links the host Vulkan loader
#
# The guest binary imports exactly one Vulkan symbol from libvulkan.so,
# vkGetInstanceProcAddr; everything else is resolved at run time.
#
# WHY A HOST BUILD OF THE GUEST PROBE
# -----------------------------------
# Without it, a guest FAIL cannot be told apart from a bug in the probe. Building
# the identical source against the KosmicKrisp ICD the guest ultimately talks to
# gives both a correctness control for the probe and a reference trace to diff a
# guest run against: a failure that reproduces on the host is a driver problem,
# one that does not is a transport problem. That distinction has decided every
# ray-tracing question in this tree so far, in both directions.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../../.." && pwd)"
NDK="${NDK:-$ROOT/third_party/android-ndk-r28c}"
API="${API:-34}"

HOST=0
if [ "${1:-}" = "--host" ]; then HOST=1; shift; fi
if [ -n "${1:-}" ]; then echo "usage: $(basename "$0") [--host]" >&2; exit 2; fi

TOOLS="$NDK/toolchains/llvm/prebuilt/darwin-x86_64/bin"
GLSLC="${GLSLC:-$NDK/shader-tools/darwin-x86_64/glslc}"
[ -x "$GLSLC" ] || { echo "missing tool: $GLSLC" >&2; exit 1; }

# --- shaders ------------------------------------------------------------------
# SPIR-V 1.4 is the *minimum* the RayQueryKHR capability requires and the most
# compatible choice: it is consumable by a Vulkan 1.1 device with VK_KHR_spirv_1_4
# as well as by 1.2/1.3 core. Targeting spv1.5 instead would silently exclude a
# 1.1 guest driver, which is not a limit worth inventing.
#
# Deliberately NOT optimized. Each module is ~1-4 KB either way, and unoptimized
# SPIR-V keeps the OpRayQuery* instructions in one-to-one correspondence with the
# GLSL — which is what makes a NIR->MSL translation bug readable when this probe
# is used to chase one. (-O would also force shaderc's optimizer to the target
# env's default SPIR-V version, 1.3 under Vulkan 1.1, and fail outright.)
#
# Three shaders, because the probe asks its question from two different pipeline
# stages: vk-rt-probe.comp for the default compute mode, and
# vk-rt-probe.{vert,frag} for --fragment, which is where every real ray-query
# application traces from. See the header of vk-rt-probe.frag.
SHADERS="vk-rt-probe.comp:compute:rq_spv
vk-rt-probe.vert:vert:rq_vert_spv
vk-rt-probe.frag:frag:rq_frag_spv"

HDR="$HERE/vk-rt-probe-spv.h"
: > "$HDR.tmp"
{
   echo "/* Generated by build-vk-rt-probe.sh from vk-rt-probe.{comp,vert,frag}."
   echo "   Do not edit. */"
} >> "$HDR.tmp"

while IFS=: read -r src stage var; do
   [ -n "$src" ] || continue
   spv="$HERE/${src%.*}.$stage.spv"
   echo "==> compiling $src to SPIR-V 1.4 ($stage)"
   "$GLSLC" --target-env=vulkan1.1 --target-spv=spv1.4 \
            -fshader-stage="$stage" "$HERE/$src" -o "$spv"
   if command -v spirv-val >/dev/null 2>&1; then
      spirv-val --target-env vulkan1.1spv1.4 "$spv"
      echo "    spirv-val: ok"
   fi
   python3 - "$spv" "$HDR.tmp" "$var" "$src" <<'PY'
import struct, sys
blob = open(sys.argv[1], 'rb').read()
assert len(blob) % 4 == 0, "SPIR-V must be a whole number of words"
words = struct.unpack('<%dI' % (len(blob) // 4), blob)
assert words[0] == 0x07230203, "bad SPIR-V magic 0x%08x" % words[0]
with open(sys.argv[2], 'a') as f:
    f.write("\n/* %s: %d bytes, SPIR-V version %d.%d */\n"
            % (sys.argv[4], len(blob), (words[1] >> 16) & 0xff, (words[1] >> 8) & 0xff))
    f.write("static const uint32_t %s[] = {\n" % sys.argv[3])
    for i in range(0, len(words), 6):
        f.write("   " + " ".join("0x%08xu," % w for w in words[i:i+6]) + "\n")
    f.write("};\n")
print("    %d bytes, %d words -> %s" % (len(blob), len(words), sys.argv[3]))
PY
done <<< "$SHADERS"

mv "$HDR.tmp" "$HDR"
echo "==> embedded all three modules in $(basename "$HDR")"

# --- probe --------------------------------------------------------------------
if [ "$HOST" = 1 ]; then
   # shellcheck disable=SC1091
   set +o pipefail; . "$ROOT/third_party/paths.sh"; set -o pipefail
   ICD="${VK_DRIVER_FILES:-$TP_KOSMICKRISP_ICD}"
   [ -f "$ICD" ] || { echo "no ICD manifest at $ICD — third_party/bootstrap.sh mesa first" >&2; exit 1; }

   echo "==> compiling vk-rt-probe for the host (arm64 macOS)"
   clang -std=c11 -O1 -g -Wall -Wextra -Wno-unused-parameter \
         -I"$HERE" -I"$(brew --prefix vulkan-headers)/include" \
         "$HERE/vk-rt-probe.c" -o "$HERE/vk-rt-probe-host" \
         -L/opt/homebrew/lib -lvulkan -lm -Wl,-rpath,/opt/homebrew/lib

   echo "==> result"
   file "$HERE/vk-rt-probe-host"
   echo
   echo "    run it with:  VK_DRIVER_FILES=$ICD $HERE/vk-rt-probe-host [--fragment]"
   exit 0
fi

CC="$TOOLS/aarch64-linux-android$API-clang"
[ -x "$CC" ] || { echo "missing tool: $CC" >&2; exit 1; }

echo "==> cross-compiling vk-rt-probe (aarch64-linux-android$API)"
"$CC" -std=c11 -O2 -g -Wall -Wextra -Wno-unused-parameter \
      -fno-omit-frame-pointer \
      -I"$HERE" \
      "$HERE/vk-rt-probe.c" \
      -o "$HERE/vk-rt-probe" \
      -lvulkan -lm

echo "==> result"
file "$HERE/vk-rt-probe"
echo "    imports from libvulkan.so:"
"$TOOLS/llvm-nm" --dynamic --undefined-only "$HERE/vk-rt-probe" \
   | awk '$NF ~ /^vk/ { print "      " $NF }'
echo "    DT_NEEDED:"
"$TOOLS/llvm-readelf" --dynamic "$HERE/vk-rt-probe" \
   | awk '/NEEDED/ { print "      " $NF }'
