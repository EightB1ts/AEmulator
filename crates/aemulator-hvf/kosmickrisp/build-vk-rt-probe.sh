#!/usr/bin/env bash
# Cross-compile vk_rt_probe for Android arm64 with the in-tree NDK.
#
# Two steps: vk-rt-probe.comp -> SPIR-V -> vk-rt-probe-spv.h (a plain uint32_t array, so the probe
# needs no files on the guest), then one clang invocation. The only shared
# library the result imports is libvulkan.so, and the only Vulkan symbol it
# imports from it is vkGetInstanceProcAddr.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
NDK="${NDK:-/Users/cam/AEmulator/third_party/android-ndk-r28c}"
API="${API:-34}"

TOOLS="$NDK/toolchains/llvm/prebuilt/darwin-x86_64/bin"
CC="$TOOLS/aarch64-linux-android$API-clang"
GLSLC="${GLSLC:-$NDK/shader-tools/darwin-x86_64/glslc}"

for t in "$CC" "$GLSLC"; do
   [ -x "$t" ] || { echo "missing tool: $t" >&2; exit 1; }
done

# --- shader -------------------------------------------------------------------
# SPIR-V 1.4 is the *minimum* the RayQueryKHR capability requires and the most
# compatible choice: it is consumable by a Vulkan 1.1 device with VK_KHR_spirv_1_4
# as well as by 1.2/1.3 core. Targeting spv1.5 instead would silently exclude a
# 1.1 guest driver, which is not a limit worth inventing.
#
# Deliberately NOT optimized. The module is 1.2 KB either way, and unoptimized
# SPIR-V keeps the OpRayQuery* instructions in one-to-one correspondence with
# vk-rt-probe.comp — which is what makes a NIR->MSL translation bug readable when this
# probe is used to chase one. (-O would also force shaderc's optimizer to the
# target env's default SPIR-V version, 1.3 under Vulkan 1.1, and fail outright.)
echo "==> compiling vk-rt-probe.comp to SPIR-V 1.4"
"$GLSLC" --target-env=vulkan1.1 --target-spv=spv1.4 \
         -fshader-stage=compute \
         "$HERE/vk-rt-probe.comp" -o "$HERE/vk-rt-probe.spv"

if command -v spirv-val >/dev/null 2>&1; then
   spirv-val --target-env vulkan1.1spv1.4 "$HERE/vk-rt-probe.spv"
   echo "    spirv-val: ok"
fi

echo "==> embedding SPIR-V as vk-rt-probe-spv.h"
python3 - "$HERE/vk-rt-probe.spv" "$HERE/vk-rt-probe-spv.h" <<'PY'
import struct, sys
blob = open(sys.argv[1], 'rb').read()
assert len(blob) % 4 == 0, "SPIR-V must be a whole number of words"
words = struct.unpack('<%dI' % (len(blob) // 4), blob)
assert words[0] == 0x07230203, "bad SPIR-V magic 0x%08x" % words[0]
with open(sys.argv[2], 'w') as f:
    f.write("/* Generated by build.sh from vk-rt-probe.comp. Do not edit. */\n")
    f.write("/* %d bytes, SPIR-V version %d.%d */\n"
            % (len(blob), (words[1] >> 16) & 0xff, (words[1] >> 8) & 0xff))
    f.write("static const uint32_t rq_spv[] = {\n")
    for i in range(0, len(words), 6):
        f.write("   " + " ".join("0x%08xu," % w for w in words[i:i+6]) + "\n")
    f.write("};\n")
print("    %d bytes, %d words" % (len(blob), len(words)))
PY

# --- probe --------------------------------------------------------------------
echo "==> cross-compiling vk_rt_probe (aarch64-linux-android$API)"
"$CC" -std=c11 -O2 -g -Wall -Wextra -Wno-unused-parameter \
      -fno-omit-frame-pointer \
      -I"$HERE" \
      "$HERE/vk-rt-probe.c" \
      -o "$HERE/vk-rt-probe" \
      -lvulkan -lm

echo "==> result"
file "$HERE/vk-rt-probe"
echo "    imports from libvulkan.so:"
"$TOOLS/llvm-nm" --dynamic --undefined-only "$HERE/vk-rt-probe" \
   | awk '$NF ~ /^vk/ { print "      " $NF }'
echo "    DT_NEEDED:"
"$TOOLS/llvm-readelf" --dynamic "$HERE/vk-rt-probe" \
   | awk '/NEEDED/ { print "      " $NF }'
