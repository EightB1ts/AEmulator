#!/usr/bin/env bash
# gen-ffi.sh — regenerate src/gfxstream/ffi.rs from the gfxstream host-renderer C ABI headers.
#
# Committed output: the default aemulator-hvf build does NOT run bindgen (no libclang needed);
# ffi.rs is only compiled when the `gfxstream` cargo feature is enabled. Re-run this if the
# upstream headers change.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
# Derive the repo root from this script's location — never hardcode an absolute path.
# <root>/crates/aemulator-hvf/gfxstream -> <root>
ROOT="$(cd "$HERE/../../.." && pwd)"
# paths.sh discovers the KosmicKrisp ICD with a glob that legitimately matches nothing before the
# first bootstrap; under `pipefail` that empty glob would abort this script.
set +o pipefail; . "$ROOT/third_party/paths.sh"; set -o pipefail
OUT="$HERE/../src/gfxstream/ffi.rs"
WRAP="$HERE/../src/gfxstream/wrapper.h"

# libclang from the Command Line Tools (Xcode-Beta's toolchain omits libclang.dylib).
export LIBCLANG_PATH="${LIBCLANG_PATH:-/Library/Developer/CommandLineTools/usr/lib}"

bindgen "$WRAP" \
    --output "$OUT" \
    --allowlist-function 'stream_renderer_.*' \
    --allowlist-function 'gfxstream_backend_.*' \
    --allowlist-function 'android_.*Opengles.*' \
    --allowlist-function 'android_.*Gles.*' \
    --allowlist-function 'android_getOpenglesVersion' \
    --allowlist-function 'android_prepareOpenglesEmulation' \
    --allowlist-function 'android_setPostCallback' \
    --allowlist-type 'stream_renderer_.*' \
    --allowlist-type 'RendererFlags' \
    --allowlist-var 'STREAM_RENDERER_.*' \
    --allowlist-var 'STREAM_BLOB_.*' \
    --allowlist-var 'STREAM_MEM_.*' \
    --default-enum-style rust_non_exhaustive \
    --no-layout-tests \
    --raw-line '// @generated by gfxstream/gen-ffi.sh via bindgen — do not edit by hand.' \
    --raw-line '#![allow(non_upper_case_globals, non_camel_case_types, non_snake_case, dead_code)]' \
    -- \
    -x c \
    -I"$TP_GFXSTREAM_SRC/host/include" \
    -I"$TP_GFXSTREAM_SRC/host/gl/gl-host-common/include" \
    -I"$TP_GFXSTREAM_SRC/include" \
    -I"$TP_AEMU_INSTALL/include" \
    -I"$TP_AEMU_SRC/host-common/include" \
    -I"$TP_AEMU_SRC/base/include"

echo "wrote $OUT"
