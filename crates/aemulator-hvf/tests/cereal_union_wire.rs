//! The guest→host wire format of `VkAccelerationStructureGeometryDataKHR`, exercised against the
//! REAL generated host decoder inside `libgfxstream_backend.dylib`.
//!
//! WHAT THIS IS GUARDING
//! ---------------------
//! `VkAccelerationStructureGeometryDataKHR` is a union whose live arm is named by a *sibling* field
//! — `VkAccelerationStructureGeometryKHR::geometryType` (vk.xml marks the member `selector`, and
//! each arm `selection`). Until the cereal generators learned about that, both sides serialized the
//! union unconditionally as its FIRST member, `triangles`, whatever it actually held.
//!
//! That is survivable for two of the three arms purely by luck, because the wire carries field
//! bytes and never padding:
//!
//! ```text
//!   triangles: sType@0 pNext@8 vertexFormat@16 vertexData@24 vertexStride@32
//!              maxVertex@40 indexType@44 indexData@48 transformData@56
//!   instances: sType@0 pNext@8 arrayOfPointers@16 data@24          <- aligns with the above
//!   aabbs:     sType@0 pNext@8 data@16          stride@24          <- does NOT
//! ```
//!
//! `aabbs.data` is a `VkDeviceOrHostAddressConstKHR`, i.e. 8 bytes at offset 16..24. The triangles
//! program transmits only 16..20 there (as `vertexFormat`) and treats 20..24 as padding, so the
//! HIGH 32 BITS OF EVERY AABB DEVICE ADDRESS WERE DROPPED. KosmicKrisp hands out addresses around
//! `0x0000_0015_0800_0000`, whose high dword is nonzero, so a procedural-geometry (AABB) BLAS built
//! through gfxstream resolved to a completely different address than the guest asked for.
//!
//! WHY IT LIVES HERE AND WHAT IT PROVES
//! ------------------------------------
//! `reservedunmarshal_*` is the function `VkDecoder` calls on every packet, generated by the era
//! codegen in `third_party/patches/gfxstream-codegen/`. This test hands it bytes laid out exactly
//! as the (fixed) guest encoder writes them and checks the struct that comes out — so it fails if
//! either the generator or the recorded patch series regresses, and it needs no guest, no GPU and
//! no VM.
//!
//! It is symmetric by construction, not by assumption: the guest encoder in
//! `third_party/patches/mesa/0007-*.patch` is generated by the same union machinery, from the same
//! `selector`/`selection` attributes, and `third_party/regen-guest-encoder.sh --opcode-diff` is the
//! standing gate that the two generators agree.
//!
//! On a runner whose gfxstream is `ci/stub-gfxstream` the symbol does not exist and the test skips
//! loudly rather than pretending to pass.

use std::ffi::{c_void, CString};
use std::os::raw::c_char;

// ---------------------------------------------------------------------------------------------
// Vulkan constants and layout, copied from <vulkan/vulkan_core.h>. Asserted below against
// size_of/offsets so a header change cannot quietly invalidate them.
// ---------------------------------------------------------------------------------------------
const VK_STRUCTURE_TYPE_MAX_ENUM: u32 = 0x7FFF_FFFF;
const ST_GEOMETRY_KHR: u32 = 1_000_150_006;
const ST_GEOMETRY_TRIANGLES_DATA_KHR: u32 = 1_000_150_005;
const ST_GEOMETRY_AABBS_DATA_KHR: u32 = 1_000_150_003;
const ST_GEOMETRY_INSTANCES_DATA_KHR: u32 = 1_000_150_004;

const VK_GEOMETRY_TYPE_TRIANGLES_KHR: u32 = 0;
const VK_GEOMETRY_TYPE_AABBS_KHR: u32 = 1;
const VK_GEOMETRY_TYPE_INSTANCES_KHR: u32 = 2;

const VK_FORMAT_R32G32B32_SFLOAT: u32 = 106;
const VK_INDEX_TYPE_UINT32: u32 = 1;
const VK_GEOMETRY_OPAQUE_BIT_KHR: u32 = 0x1;

/// A real KosmicKrisp device address: `MTLHeap` placements land far above 4 GiB, so the high dword
/// is what the old code threw away. Every assertion in this file exists to catch its loss.
const AABB_ADDR: u64 = 0x0000_0015_0800_0000;

/// `VkAccelerationStructureGeometryKHR`, as the C compiler lays it out on arm64 macOS. The union is
/// an opaque 64-byte block because Rust unions of C structs buy nothing here — the arms are read
/// back at their C offsets, which is exactly what the decoder wrote.
#[repr(C)]
#[derive(Clone, Copy)]
struct GeometryKhr {
    s_type: u32,
    _pad0: u32,
    p_next: *const c_void,
    geometry_type: u32,
    _pad1: u32,
    geometry: [u8; 64],
    flags: u32,
    _pad2: u32,
}

impl GeometryKhr {
    fn zeroed() -> Self {
        // Poisoned, not zeroed: a field the decoder fails to write must not read back as a
        // plausible value. 0xCD everywhere makes an untouched u64 read 0xCDCD_CDCD_CDCD_CDCD.
        unsafe { std::mem::transmute::<[u8; 96], GeometryKhr>([0xCD; 96]) }
    }
    fn arm_u32(&self, off: usize) -> u32 {
        u32::from_ne_bytes(self.geometry[off..off + 4].try_into().unwrap())
    }
    fn arm_u64(&self, off: usize) -> u64 {
        u64::from_ne_bytes(self.geometry[off..off + 8].try_into().unwrap())
    }
}

/// The generated decoder: `gfxstream::vk::reservedunmarshal_VkAccelerationStructureGeometryKHR`.
type ReservedUnmarshalGeometry =
    unsafe extern "C" fn(*mut c_void, u32, *mut GeometryKhr, *mut *const u8);

/// Itanium-mangled name of that function. Verified with
/// `nm -gU third_party/gfxstream/build-host/libgfxstream_backend.dylib`.
const SYMBOL: &str = "_ZN9gfxstream2vk52reservedunmarshal_VkAccelerationStructureGeometryKHREPNS0_\
                      12VulkanStreamE15VkStructureTypeP34VkAccelerationStructureGeometryKHRPPh";

/// Load the decoder out of the renderer dylib, or `None` when this build has no real renderer
/// (`ci/stub-gfxstream`), in which case the caller must skip.
fn load_decoder() -> Option<ReservedUnmarshalGeometry> {
    let dylib = format!(
        "{}/libgfxstream_backend.dylib",
        env!("AEMU_GFXSTREAM_BUILD_HOST")
    );
    let path = CString::new(dylib.as_str()).unwrap();
    // RTLD_LOCAL keeps the renderer's symbols out of the global namespace; nothing else in this
    // test process wants them.
    let handle = unsafe { libc::dlopen(path.as_ptr(), libc::RTLD_LAZY | libc::RTLD_LOCAL) };
    assert!(
        !handle.is_null(),
        "dlopen({dylib}) failed — build.rs already proved the file exists, so this is a load \
         failure, not an absence"
    );
    // SYMBOL is spelled the way dlsym wants it: the Itanium mangling, WITHOUT the extra leading
    // underscore Mach-O prepends and nm prints (nm shows `__ZN9gfxstream…`, dlsym wants
    // `_ZN9gfxstream…`).
    let name = CString::new(SYMBOL).unwrap();
    let sym = unsafe { libc::dlsym(handle, name.as_ptr() as *const c_char) };
    if sym.is_null() {
        return None;
    }
    Some(unsafe { std::mem::transmute::<*mut c_void, ReservedUnmarshalGeometry>(sym) })
}

/// Builds the packet body for one `VkAccelerationStructureGeometryKHR`, field by field, in exactly
/// the order the generated encoder emits: scalars little-endian and unaligned, `pNext` as a
/// big-endian u32 size word (0 == absent), and the union as ONE arm chosen by `geometryType`.
struct Wire(Vec<u8>);

impl Wire {
    fn new(geometry_type: u32) -> Self {
        let mut w = Wire(Vec::new());
        w.u32(ST_GEOMETRY_KHR);
        w.pnext_absent();
        w.u32(geometry_type);
        w
    }
    fn u32(&mut self, v: u32) {
        self.0.extend_from_slice(&v.to_le_bytes());
    }
    fn u64(&mut self, v: u64) {
        self.0.extend_from_slice(&v.to_le_bytes());
    }
    /// `VulkanStream::putBe32(0)` — the generated reader runs `fromBe32` over these four bytes.
    fn pnext_absent(&mut self) {
        self.0.extend_from_slice(&0u32.to_be_bytes());
    }

    fn decode(&self, f: ReservedUnmarshalGeometry) -> (GeometryKhr, usize) {
        let mut out = GeometryKhr::zeroed();
        // SLACK. A decoder that disagrees with the encoder about the union reads PAST the packet —
        // that is the whole failure mode under test — so the buffer is over-allocated. Without it
        // the negative case is an out-of-bounds read rather than a clean assertion failure.
        let mut buf = self.0.clone();
        buf.resize(self.0.len() + 128, 0xAA);
        let mut cursor: *const u8 = buf.as_ptr();
        // A null VulkanStream is safe HERE and only here: the generated body dereferences the
        // stream solely inside `if (pNext_size)`, to allocate an extension struct. Every pNext in
        // these packets is absent, so that branch is never taken. If a future generator revision
        // starts touching the stream unconditionally, this test segfaults — which is the correct,
        // loud failure.
        unsafe {
            f(
                std::ptr::null_mut(),
                VK_STRUCTURE_TYPE_MAX_ENUM,
                &mut out,
                &mut cursor,
            )
        };
        let consumed = (cursor as usize) - (buf.as_ptr() as usize);
        (out, consumed)
    }
}

#[test]
fn struct_layout_matches_the_c_abi() {
    assert_eq!(std::mem::size_of::<GeometryKhr>(), 96);
    assert_eq!(std::mem::align_of::<GeometryKhr>(), 8);
}

/// THE REGRESSION TEST. An AABB geometry whose device address has a nonzero high dword must arrive
/// whole.
#[test]
fn aabb_device_address_keeps_its_high_dword() {
    let Some(decode) = load_decoder() else {
        eprintln!(
            "SKIP: {SYMBOL} is absent — this gfxstream is ci/stub-gfxstream, not a real renderer \
             build. Run third_party/bootstrap.sh gfxstream for real coverage."
        );
        return;
    };

    const STRIDE: u64 = 24; // sizeof(VkAabbPositionsKHR)
    let mut w = Wire::new(VK_GEOMETRY_TYPE_AABBS_KHR);
    w.u32(ST_GEOMETRY_AABBS_DATA_KHR);
    w.pnext_absent();
    w.u64(AABB_ADDR);
    w.u64(STRIDE);
    w.u32(VK_GEOMETRY_OPAQUE_BIT_KHR);

    let (g, consumed) = w.decode(decode);

    assert_eq!(g.s_type, ST_GEOMETRY_KHR);
    assert!(g.p_next.is_null());
    assert_eq!(g.geometry_type, VK_GEOMETRY_TYPE_AABBS_KHR);
    // VkAccelerationStructureGeometryAabbsDataKHR: sType@0, pNext@8, data@16, stride@24.
    assert_eq!(g.arm_u32(0), ST_GEOMETRY_AABBS_DATA_KHR);
    assert_eq!(
        g.arm_u64(16),
        AABB_ADDR,
        "AABB deviceAddress was truncated. Got {:#018x}, want {AABB_ADDR:#018x} — a low-dword-only \
         value means the union is being marshalled as its `triangles` arm again",
        g.arm_u64(16)
    );
    // Stated separately from the equality above so the failure is unmistakable in the log.
    assert_eq!(
        (g.arm_u64(16) >> 32) as u32,
        (AABB_ADDR >> 32) as u32,
        "the HIGH 32 BITS of the AABB device address were dropped"
    );
    assert_eq!(g.arm_u64(24), STRIDE);
    assert_eq!(g.flags, VK_GEOMETRY_OPAQUE_BIT_KHR);
    // 4 sType + 4 pNext + 4 geometryType + (4 + 4 + 8 + 8) arm + 4 flags. The old encoding spent 56
    // bytes on this arm and still lost half the address.
    assert_eq!(consumed, 40);
}

/// The other two arms, so the switch is proven in full rather than only where it was broken.
/// `triangles` is byte-for-byte what the old unconditional code emitted, which is why ray-traced
/// triangle geometry worked all along.
#[test]
fn triangles_and_instances_arms_round_trip() {
    let Some(decode) = load_decoder() else {
        eprintln!("SKIP: {SYMBOL} is absent (ci/stub-gfxstream build)");
        return;
    };

    let vertex_data = 0x0000_0015_0800_1000u64;
    let index_data = 0x0000_0015_0800_2000u64;
    let transform_data = 0x0000_0015_0800_3000u64;
    let mut w = Wire::new(VK_GEOMETRY_TYPE_TRIANGLES_KHR);
    w.u32(ST_GEOMETRY_TRIANGLES_DATA_KHR);
    w.pnext_absent();
    w.u32(VK_FORMAT_R32G32B32_SFLOAT);
    w.u64(vertex_data);
    w.u64(12); // vertexStride
    w.u32(2); // maxVertex
    w.u32(VK_INDEX_TYPE_UINT32);
    w.u64(index_data);
    w.u64(transform_data);
    w.u32(VK_GEOMETRY_OPAQUE_BIT_KHR);

    let (g, consumed) = w.decode(decode);
    assert_eq!(g.geometry_type, VK_GEOMETRY_TYPE_TRIANGLES_KHR);
    assert_eq!(g.arm_u32(0), ST_GEOMETRY_TRIANGLES_DATA_KHR);
    assert_eq!(g.arm_u32(16), VK_FORMAT_R32G32B32_SFLOAT);
    assert_eq!(g.arm_u64(24), vertex_data);
    assert_eq!(g.arm_u64(32), 12);
    assert_eq!(g.arm_u32(40), 2);
    assert_eq!(g.arm_u32(44), VK_INDEX_TYPE_UINT32);
    assert_eq!(g.arm_u64(48), index_data);
    assert_eq!(g.arm_u64(56), transform_data);
    assert_eq!(g.flags, VK_GEOMETRY_OPAQUE_BIT_KHR);
    assert_eq!(consumed, 68);

    // Instances: sType@0, pNext@8, arrayOfPointers@16, data@24. Its `data` happens to land on the
    // triangles `vertexData` slot, which is why TLAS builds also survived the bug — but the arm is
    // 32 bytes shorter on the wire now that only its own fields are sent.
    let instances_addr = 0x0000_0015_0900_0000u64;
    let mut w = Wire::new(VK_GEOMETRY_TYPE_INSTANCES_KHR);
    w.u32(ST_GEOMETRY_INSTANCES_DATA_KHR);
    w.pnext_absent();
    w.u32(0); // arrayOfPointers = VK_FALSE
    w.u64(instances_addr);
    w.u32(0); // flags

    let (g, consumed) = w.decode(decode);
    assert_eq!(g.geometry_type, VK_GEOMETRY_TYPE_INSTANCES_KHR);
    assert_eq!(g.arm_u32(0), ST_GEOMETRY_INSTANCES_DATA_KHR);
    assert_eq!(g.arm_u32(16), 0);
    assert_eq!(g.arm_u64(24), instances_addr);
    assert_eq!(g.flags, 0);
    assert_eq!(consumed, 36);
}
