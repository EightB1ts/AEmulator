//! `deepcopy_*` may not DEREFERENCE a pointer arm of a union — asserted against the generated
//! sources on BOTH sides of the wire.
//!
//! WHAT THIS IS GUARDING, AND WHY IT IS A SOURCE SCAN
//! -------------------------------------------------
//! A union's arms overlap, so every arm but the live one reads bytes that belong to a different arm.
//! `deepcopy` is the only cereal emitter that *dereferences* what it reads, and it has no
//! discriminant: its signature is `(Allocator*, VkStructureType, const T* from, T* to)` at every
//! call site in `VkEncoder`, so the `selector` machinery that taught `count_`/`marshal_`/
//! `reservedmarshal_` to switch on a sibling field cannot reach it.
//!
//! The upstream generator nevertheless emitted, for `VkDeviceOrHostAddress{,Const}KHR`:
//!
//! ```c
//! *to = *from;
//! to->hostAddress = nullptr;
//! if (from->hostAddress) to->hostAddress = (void*)alloc->dupArray(from->hostAddress, 1);
//! ```
//!
//! and `deepcopy_VkAccelerationStructureGeometryDataKHR` recurses into ALL THREE of its arms. So for
//! a geometry holding `triangles`, the `aabbs` arm's `data` — which overlaps `triangles::vertexFormat`
//! plus four bytes of padding, i.e. the small integer 106 (`VK_FORMAT_R32G32B32_SFLOAT`) — was passed
//! to `dupArray`, which read address `0x6a`.
//!
//! That is not theoretical. It is a **SIGSEGV in the guest ICD** inside
//! `vkGetAccelerationStructureBuildSizesKHR`, on the first acceleration-structure call an
//! application makes, reproduced by `vk-rt-probe` and by a real ray-query app at the same
//! instruction. It shipped once already: the fix lived as a HAND EDIT inside a generated file, and
//! re-exporting `patches/mesa/0007-*` regenerated that file and dropped it.
//!
//! The fix is now in `cereal/deepcopy.py` in both generator copies (guest: `patches/mesa/0007-*`;
//! host: `patches/gfxstream-codegen/0005-union-pointer-arms-are-not-dereferenced.patch`), so
//! regeneration reproduces it. This test asserts the *property* rather than the patch, and it scans
//! the generated C++ rather than the generator, because the generated C++ is what actually ships:
//! `regen-*.sh --reproduce` proves generator == checkout, and this proves the checkout is safe. Both
//! are needed — the hand-edit era passed neither.
//!
//! Hermetic: no GPU, no VM, no dylib. When the checkouts are absent (the hosted CI runner has no
//! `third_party/mesa`) it skips loudly rather than pretending to pass.

use std::path::{Path, PathBuf};

/// Repo root, derived from this crate's manifest dir — `crates/aemulator-hvf/../..`.
fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("crates/aemulator-hvf is two levels below the repo root")
        .to_path_buf()
}

/// Every generated deepcopy translation unit this repo ships, guest and host.
fn generated_deepcopy_sources() -> Vec<PathBuf> {
    let root = repo_root();
    vec![
        root.join("third_party/mesa/src/gfxstream/guest/vulkan_enc/autogenerated/goldfish_vk_deepcopy_guest.cpp"),
        root.join("third_party/gfxstream/host/vulkan/cereal/common/goldfish_vk_deepcopy.cpp"),
    ]
}

/// The body of `void <prefix><name>(...)` — from the signature to the first line that is exactly
/// `}`, which is how clang-format lays these files out (Google style, no nesting at file scope).
fn function_body<'a>(src: &'a str, name: &str) -> Option<&'a str> {
    let needle = format!("void {name}(");
    let start = src.find(&needle)?;
    let rest = &src[start..];
    let end = rest.find("\n}")?;
    Some(&rest[..end])
}

/// The two unions whose only non-scalar arm is a pointer, and which every acceleration-structure
/// build passes a *device* address in. These are the ones that crashed.
const DEVICE_OR_HOST_ADDRESS_UNIONS: [&str; 2] = [
    "deepcopy_VkDeviceOrHostAddressKHR",
    "deepcopy_VkDeviceOrHostAddressConstKHR",
];

#[test]
fn device_or_host_address_deepcopy_never_dereferences_the_host_arm() {
    let mut checked = 0usize;

    for path in generated_deepcopy_sources() {
        if !path.exists() {
            eprintln!(
                "SKIP: {} is absent — this tree has no third_party checkout (run \
                 third_party/bootstrap.sh for real coverage)",
                path.display()
            );
            continue;
        }
        let src = std::fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));

        for name in DEVICE_OR_HOST_ADDRESS_UNIONS {
            let body = function_body(&src, name).unwrap_or_else(|| {
                panic!(
                    "{} does not define {name} — the generator's output shape changed; this guard \
                     must be updated rather than deleted",
                    path.display()
                )
            });

            assert!(
                !body.contains("dupArray"),
                "{}: {name} calls dupArray on `hostAddress`.\n\
                 That arm holds a DEVICE address on every VK_ACCELERATION_STRUCTURE_BUILD_TYPE_\
                 DEVICE_KHR build, so this dereferences a non-CPU address and SIGSEGVs the guest \
                 ICD in vkGetAccelerationStructureBuildSizesKHR.\n\
                 The fix belongs in cereal/deepcopy.py (skip union members with \
                 pointerIndirectionLevels > 0), NOT as a hand edit here — a hand edit is erased by \
                 the next regeneration, which is exactly how this shipped once.\n\
                 body was:\n{body}",
                path.display()
            );
            assert!(
                body.contains("*to = *from"),
                "{}: {name} no longer copies the union's bytes at all — the value has to survive \
                 even though the pointer is not followed.\nbody was:\n{body}",
                path.display()
            );
            checked += 1;
        }
    }

    assert!(
        checked > 0,
        "no generated deepcopy source was found, so this test asserted nothing. It must not pass \
         silently: run third_party/bootstrap.sh, or keep it skipping only on a runner that has no \
         checkouts at all."
    );
}

/// The union that made the pointer arm reachable in the first place. `deepcopy` walks all three of
/// its arms — that stays true and is fine, *provided* the arms' own pointer members are not
/// followed, which is what the test above pins. This test states the dependency explicitly so that
/// anyone who "fixes" the recursion here knows the other half exists.
#[test]
fn acceleration_structure_geometry_union_still_walks_every_arm() {
    let mut checked = 0usize;
    for path in generated_deepcopy_sources() {
        if !path.exists() {
            continue;
        }
        let src = std::fs::read_to_string(&path).unwrap();
        let Some(body) = function_body(&src, "deepcopy_VkAccelerationStructureGeometryDataKHR")
        else {
            continue;
        };
        for arm in [
            "deepcopy_VkAccelerationStructureGeometryTrianglesDataKHR",
            "deepcopy_VkAccelerationStructureGeometryAabbsDataKHR",
            "deepcopy_VkAccelerationStructureGeometryInstancesDataKHR",
        ] {
            assert!(
                body.contains(arm),
                "{}: deepcopy_VkAccelerationStructureGeometryDataKHR no longer calls {arm}.\n\
                 That is not necessarily wrong, but it changes the premise of \
                 device_or_host_address_deepcopy_never_dereferences_the_host_arm: that test is \
                 what makes walking a NON-LIVE arm harmless. Re-derive both together.",
                path.display()
            );
        }
        checked += 1;
    }
    assert!(checked > 0 || !repo_root().join("third_party/mesa").exists());
}
